import type { EdaPlacedComponent, EdaWire } from "./types";
import { EDA_COMPONENT_CATALOG } from "./componentsCatalog";

export interface EdaPreset {
  id: string;
  name: string;
  badge: string;
  description: string;
  instrumentFocus: "oscilloscope" | "bode_analyzer" | "logic_analyzer" | "multimeter" | "netlist";
  components: EdaPlacedComponent[];
  wires: EdaWire[];
}

function findDef(type: string) {
  const def = EDA_COMPONENT_CATALOG.find((c) => c.type === type);
  if (!def) throw new Error(`Component definition not found for type: ${type}`);
  return def;
}

